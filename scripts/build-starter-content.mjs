// Generates supabase/seed.sql and public/templates/*.csv from content/starter-questions.mjs
// Run: npm run content:build
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { starterQuestions } from '../content/starter-questions.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const IMPORT_COLUMNS = [
  'question_id', 'learning_mode', 'cefr_level', 'school_level', 'category', 'subcategory', 'difficulty',
  'question_text', 'passage', 'option_a', 'option_b', 'option_c', 'option_d', 'correct_answer',
  'explanation', 'distractor_analysis', 'learning_objective', 'skill_assessed', 'tags', 'status',
];

const toRow = (q) => ({ ...q, question_id: q.code });
const csvCell = (v) => {
  const s = String(v ?? '');
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const csv = (rows) =>
  [IMPORT_COLUMNS.join(','), ...rows.map((r) => IMPORT_COLUMNS.map((c) => csvCell(r[c])).join(','))].join('\r\n') + '\r\n';

mkdirSync(resolve(root, 'public/templates'), { recursive: true });
writeFileSync(resolve(root, 'public/templates/beo-starter-questions.csv'), csv(starterQuestions.map(toRow)));
writeFileSync(resolve(root, 'public/templates/beo-question-import-template.csv'), csv([toRow(starterQuestions[0])]));

// seed.sql: run each question through admin_save_question logic without auth (direct inserts)
const lit = (v) => (v === undefined || v === null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const sql = [
  '-- AUTO-GENERATED by scripts/build-starter-content.mjs — do not edit by hand.',
  '-- Local development seed: starter question bank (original BEO content).',
  ...starterQuestions.map((q) => {
    const opts = ['a', 'b', 'c', 'd']
      .filter((l) => q[`option_${l}`])
      .map((l) => `((select id from q), '${l.toUpperCase()}', ${lit(q[`option_${l}`])}, ${q.correct_answer === l.toUpperCase()})`)
      .join(',\n  ');
    const tags = (q.tags || '').split(',').map((t) => t.trim().toLowerCase()).filter(Boolean);
    return `with q as (
  insert into public.questions (code, learning_mode, cefr_level, school_level, category_id, subcategory, difficulty,
    question_text, passage, explanation, distractor_analysis, learning_objective, skill_assessed, status)
  values (${lit(q.code)}, ${lit(q.learning_mode)}, ${lit(q.cefr_level)}, ${lit(q.school_level)},
    (select id from public.question_categories where slug = ${lit(q.category)}), ${lit(q.subcategory)}, ${lit(q.difficulty)},
    ${lit(q.question_text)}, ${lit(q.passage)}, ${lit(q.explanation)}, ${lit(q.distractor_analysis)},
    ${lit(q.learning_objective)}, ${lit(q.skill_assessed)}, ${lit(q.status)})
  returning id
), o as (
  insert into public.question_options (question_id, label, option_text, is_correct) values
  ${opts}
)
insert into public.question_tags (question_id, tag)
select (select id from q), t from unnest(array[${tags.map(lit).join(', ') || "''"}]::text[]) t where t <> '';`;
  }),
].join('\n\n');
writeFileSync(resolve(root, 'supabase/seed.sql'), sql + '\n');
console.log(`Built ${starterQuestions.length} starter questions → seed.sql + CSV templates`);
